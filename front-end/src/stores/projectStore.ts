import { create } from "zustand";
import { ZoomKeyframe, OpenedProject, WaveformOverview, PlaybackStatus, ZoomGeneration, ZoomSuggestion, ProjectZoom } from "../lib/types";
import { shareSequence } from "../lib/sequence";
import { useSettingsStore } from "./settingsStore";

const RECENT_PROJECTS_KEY = "aeroedits.recentProjects";
const MAX_RECENT_PROJECTS = 8;

function loadStoredRecentProjects(): string[] {
  if (typeof localStorage === "undefined") return [];
  try {
    const raw = localStorage.getItem(RECENT_PROJECTS_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed)) {
      return parsed.filter((item): item is string => typeof item === "string" && item.trim().length > 0);
    }
  } catch {
    // ignore parse error
  }
  return [];
}

function saveStoredRecentProjects(projects: string[]) {
  if (typeof localStorage === "undefined") return;
  try {
    localStorage.setItem(RECENT_PROJECTS_KEY, JSON.stringify(projects));
  } catch {
    // ignore save error
  }
}

function barsFromSuggestion(suggestion: ZoomSuggestion, pending: boolean, source?: ProjectZoom["source"]): ZoomKeyframe[] {
  // The backend places every zoom; none left (its footage was cut) means no bar at all.
  const used = (suggestion.editedRanges ?? []).filter((range) => range.endUs > range.startUs);
  return used.map((range, index) => ({
    id: used.length === 1 ? suggestion.id : `${suggestion.id}-${index}`,
    zoomId: suggestion.id,
    tUs: range.startUs,
    endUs: range.endUs,
    sourceStartUs: suggestion.sourceStartUs,
    sourceEndUs: suggestion.sourceEndUs,
    normX: suggestion.centerX,
    normY: suggestion.centerY,
    scale: suggestion.scale,
    durationMs: Math.round((range.endUs - range.startUs) / 1000),
    transitionMs: Math.round(suggestion.transitionUs / 1000),
    origin: suggestion.origin,
    contributingEventSeqs: suggestion.contributingEventSeqs,
    source,
    pending,
    isAutoGenerated: pending || source === "generated",
  }));
}

function mergeZoomBars(persisted: ProjectZoom[] | undefined, pending: ZoomSuggestion[]): ZoomKeyframe[] {
  const persistedBars = (persisted ?? []).flatMap((zoom) =>
    barsFromSuggestion(
      {
        id: zoom.id,
        sourceStartUs: zoom.sourceStartUs,
        sourceEndUs: zoom.sourceEndUs,
        centerX: zoom.centerX,
        centerY: zoom.centerY,
        scale: zoom.scale,
        transitionUs: zoom.transitionUs,
        origin: zoom.origin,
        contributingEventSeqs: zoom.contributingEventSeqs ?? [],
        editedRanges: zoom.editedRanges ?? [],
      },
      false,
      zoom.source,
    ),
  );
  const pendingBars = pending.flatMap((suggestion) => barsFromSuggestion(suggestion, true));
  return [...persistedBars, ...pendingBars].sort((a, b) => a.tUs - b.tUs || a.id.localeCompare(b.id));
}

interface ProjectStore {
  openedProject: OpenedProject | null;
  projectPath: string | null;
  recentProjects: string[];
  playbackGeneration: number;
  playbackError: string | null;
  previewAvailable: boolean;
  applyPlaybackStatus: (status: PlaybackStatus) => void;
  loadOpenedProject: (project: OpenedProject, projectPath?: string) => void;
  clearProject: () => void;
  /** Waveforms by sound (`<asset>.<stream>`), over its own time. */
  waveforms: Record<string, WaveformOverview>;
  setWaveform: (key: string, overview: WaveformOverview) => void;
  zoomKeyframes: ZoomKeyframe[];
  pendingZoomSuggestions: ZoomSuggestion[];
  zoomDiagnostics: string[];
  /** The zoom picked on the timeline lane or in the Zoom panel. */
  selectedZoomId?: string;
  /** The clips selected on the timeline (linked partners included); the Inspector shows the first. */
  selectedClipIds: string[];
  /** The short shown as the timeline (the Shorts workspace), if any. */
  viewShort?: string;
  setViewShort: (shortId: string | undefined) => void;
  /** The short playing instead of the video (set by the Shorts workspace). */
  playbackShortId?: string;
  /** How fast playback goes (1, 1.25, 1.5 or 2), as the engine reports it. */
  playbackSpeed: number;
  /** Bumped whenever a transcript changes, so captions and the transcript panel reload. */
  captionsVersion: number;
  /** Marks transcripts changed, so captions and the transcript panel reload. */
  bumpCaptions: () => void;
  /** The timeline's selection, shared so other panels can act on it. */
  timelineSelection: { startUs: number; endUs: number } | null;
  currentTimeUs: number;
  durationUs: number;
  isPlaying: boolean;

  // Actions
  setProjectPath: (path: string | null) => void;
  addRecentProject: (path: string) => void;
  removeRecentProject: (path: string) => void;
  clearRecentProjects: () => void;
  setCurrentTimeUs: (timeUs: number) => void;
  setIsPlaying: (isPlaying: boolean) => void;
  togglePlayPause: () => void;
  applyZoomGeneration: (generation: Pick<ZoomGeneration, "suggestions" | "diagnostics">) => void;
  setSelectedZoomId: (id?: string) => void;
  setSelectedClipIds: (ids: string[]) => void;
  setTimelineSelection: (selection: { startUs: number; endUs: number } | null) => void;
  /** Applies an edit's result. `remote` marks one not asked for here (an agent's edit, or a
   *  short's view): it is applied only if newer. Settles once applied (while showing a short,
   *  once the short's view of it is in). */
  applyOpenedProject: (project: OpenedProject, options?: { remote?: boolean }) => Promise<void>;
}

export const useProjectStore = create<ProjectStore>((set, get) => ({
  openedProject: null,
  projectPath: null,
  recentProjects: loadStoredRecentProjects(),
  playbackGeneration: 0,
  playbackError: null,
  previewAvailable: false,
  playbackSpeed: 1,
  setProjectPath: (path) => set({ projectPath: path }),
  addRecentProject: (path) => {
    const clean = path.trim();
    if (!clean) return;
    const current = get().recentProjects.filter((p) => p !== clean);
    const updated = [clean, ...current].slice(0, MAX_RECENT_PROJECTS);
    saveStoredRecentProjects(updated);
    set({ recentProjects: updated });
  },
  removeRecentProject: (path) => {
    const updated = get().recentProjects.filter((p) => p !== path);
    saveStoredRecentProjects(updated);
    set({ recentProjects: updated });
  },
  clearRecentProjects: () => {
    saveStoredRecentProjects([]);
    set({ recentProjects: [] });
  },
  applyPlaybackStatus: (status) => set((state) => {
    if (state.openedProject?.projectHandle !== status.projectHandle || status.generation < state.playbackGeneration) return state;
    // The engine plays something not on show (a short while editing the video, or the video
    // in Shorts): note it, but keep the playhead of what is shown.
    const next: Partial<ProjectStore> =
      (status.shortId ?? undefined) !== state.viewShort
        ? { playbackShortId: status.shortId, isPlaying: false, playbackGeneration: status.generation, playbackSpeed: status.speed ?? 1 }
        : {
            currentTimeUs: Math.min(status.positionUs, state.durationUs),
            isPlaying: status.state === "playing",
            playbackGeneration: status.generation,
            playbackError: status.error,
            previewAvailable: status.previewAvailable,
            playbackShortId: status.shortId,
            playbackSpeed: status.speed ?? 1,
          };
    // Polled many times a second: nothing changed means nothing to tell the components.
    const changed = (Object.keys(next) as (keyof ProjectStore)[]).some((key) => !Object.is(next[key], state[key]));
    return changed ? next : state;
  }),
  loadOpenedProject: (project, projectPath) => {
    const resolvedPath = projectPath ?? project.projectPath ?? get().projectPath ?? undefined;
    if (resolvedPath) {
      get().addRecentProject(resolvedPath);
    }
    if (project.layout) {
      useSettingsStore.getState().hydrateLayout(project.layout);
    }
    set({
      openedProject: project,
      projectPath: resolvedPath ?? null,
      playbackGeneration: 0, playbackError: null, previewAvailable: false,
      // A short of the project before has no place in this one (Shorts picks one again).
      viewShort: undefined,
      playbackShortId: undefined,
      durationUs: project.durationUs,
      waveforms: {},
      selectedClipIds: [],
      currentTimeUs: 0,
      isPlaying: false,
      pendingZoomSuggestions: [],
      zoomKeyframes: mergeZoomBars(project.zooms, []),
      zoomDiagnostics: [],
    });
  },
  clearProject: () => {
    useSettingsStore.setState({ layoutOwnedByProject: false });
    set({
      openedProject: null,
      projectPath: null,
      playbackError: null,
      previewAvailable: false,
      viewShort: undefined,
      playbackShortId: undefined,
      waveforms: {},
      selectedClipIds: [],
      durationUs: 0,
      currentTimeUs: 0,
      isPlaying: false,
      zoomKeyframes: [],
      pendingZoomSuggestions: [],
      zoomDiagnostics: [],
    });
  },
  waveforms: {},
  setWaveform: (key, overview) => set((state) => ({ waveforms: { ...state.waveforms, [key]: overview } })),
  zoomKeyframes: [],
  pendingZoomSuggestions: [],
  zoomDiagnostics: [],
  selectedZoomId: undefined,
  selectedClipIds: [],
  captionsVersion: 0,
  viewShort: undefined,
  setViewShort: (viewShort) => set({ viewShort }),
  playbackShortId: undefined,
  bumpCaptions: () => set((state) => ({ captionsVersion: state.captionsVersion + 1 })),
  timelineSelection: null,
  currentTimeUs: 0,
  durationUs: 0,
  isPlaying: false,

  setCurrentTimeUs: (timeUs) => {
    const { durationUs } = get();
    const clamped = Math.max(0, Math.min(timeUs, durationUs));
    set({ currentTimeUs: clamped });
  },

  setIsPlaying: (isPlaying) => set({ isPlaying }),

  togglePlayPause: () => set((state) => ({ isPlaying: !state.isPlaying })),

  setSelectedZoomId: (selectedZoomId) => set({ selectedZoomId }),
  setSelectedClipIds: (selectedClipIds) => set({ selectedClipIds }),
  setTimelineSelection: (timelineSelection) => set({ timelineSelection }),

  applyZoomGeneration: (generation) =>
    set((state) => ({
      zoomDiagnostics: generation.diagnostics,
      pendingZoomSuggestions: generation.suggestions,
      zoomKeyframes: mergeZoomBars(state.openedProject?.zooms, generation.suggestions),
    })),


  applyOpenedProject: async (project, options) => {
    const current = get().openedProject;
    // A window showing a short turns every project it is handed into that short's view.
    const viewShort = get().viewShort;
    // A short removed by this revision has no view: the project as it is shows the list without it.
    const removed =
      !!viewShort &&
      project.projectHandle === current?.projectHandle &&
      project.revision >= current.revision &&
      !(project.shorts ?? []).some((short) => short.id === viewShort);
    if (removed) set({ viewShort: undefined });
    if (viewShort && !removed && project.shortView !== viewShort) {
      // Done once the view is in, so the next save goes out on this revision.
      return api
        .projectShortView(project.projectHandle, viewShort)
        .then((view) => get().applyOpenedProject(view, options))
        .catch(() => undefined);
    }
    // An older revision is stale, whether an agent's or a late reply to an edit here; an
    // agent's same revision is too. A different view of it (a short's) is not.
    if (
      current &&
      project.projectHandle === current.projectHandle &&
      project.shortView === current.shortView &&
      (project.revision < current.revision || (options?.remote && project.revision === current.revision))
    ) {
      return;
    }
    set((state) => {
      if (state.openedProject?.projectHandle !== project.projectHandle) return state;
      const taken = new Set([
        ...(project.zooms ?? []).map((zoom) => zoom.id),
        ...(project.dismissedZoomIds ?? []),
      ]);
      const pending = state.pendingZoomSuggestions.filter((suggestion) => !taken.has(suggestion.id));
      if (project.layout) {
        useSettingsStore.getState().hydrateLayout(project.layout);
      }
      const clipIds = new Set(project.sequence.tracks.flatMap((t) => t.clips.map((c) => c.id)));
      const kept = state.selectedClipIds.filter((id) => clipIds.has(id));
      // Clips the edit left alone keep their objects, so only the changed ones re-render.
      const sequence = state.openedProject?.shortView === project.shortView ? shareSequence(state.openedProject?.sequence, project.sequence) : project.sequence;
      return {
        openedProject: sequence === project.sequence ? project : { ...project, sequence },
        durationUs: project.durationUs,
        currentTimeUs: Math.min(state.currentTimeUs, project.durationUs),
        selectedClipIds: kept.length === state.selectedClipIds.length ? state.selectedClipIds : kept,
        pendingZoomSuggestions: pending,
        zoomKeyframes: mergeZoomBars(project.zooms, pending),
      };
    });
  },
}));
